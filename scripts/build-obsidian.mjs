import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {defaults,themeTokens} from '../src/palette.ts';
import {designTokens} from '../src/core/design.ts';
import {obsidianColors} from '../ports/obsidian/colors.ts';
import {transformSync} from 'esbuild';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=root+'ports/obsidian/';
mkdirSync(output,{recursive:true});
const block=(selector,tokens)=>`${selector}{\n${Object.entries(tokens).map(([k,v])=>`${k}:${v};`).join('\n')}\n}\n`;
const adapterCss=readFileSync(root+'ports/obsidian/src/colors.css','utf8')+'\n'+readFileSync(root+'ports/obsidian/src/theme.css','utf8')+'\n'+readFileSync(root+'ports/obsidian/src/plugins.css','utf8');
const sharedDesign=designTokens();
// Keep only the adapter's palette dependencies; the shared core still exports every scale.
const variableReferences=value=>[...value.matchAll(/var\(\s*(--[\w-]+)/g)].map(match=>match[1]);
function adapterTokens(tokens) {
 const needed=new Set(variableReferences(adapterCss+'\n'+Object.values(sharedDesign).join('\n')));
 const queue=[...needed];
 while(queue.length){
  const key=queue.pop();
  for(const dependency of variableReferences(tokens[key]??''))if(!needed.has(dependency)){
   needed.add(dependency);queue.push(dependency);
  }
 }
 return Object.fromEntries(Object.entries(tokens).filter(([key])=>needed.has(key)));
}
let css='/*! Arcubic — generated by npm run build:obsidian. Font licenses in licenses/. */\n';
const fonts=[
 {package:'@fontsource-variable/lora',name:'Lora'},
 {package:'@fontsource/geist-mono',name:'Geist-Mono'},
 {package:'@fontsource/chakra-petch',name:'Chakra-Petch'},
];
// Preserve every copyright notice; include the identical OFL body only once.
const fontLicenses=fonts.map(font=>readFileSync(root+`node_modules/${font.package}/LICENSE`,'utf8'));
const licenseParts=fontLicenses.map(license=>{const split=license.indexOf('\n\n');return [license.slice(0,split),license.slice(split+2)];});
if(!licenseParts.every(([,body])=>body===licenseParts[0][1]))throw new Error('Font license bodies differ; update license bundling.');
css+=`/*! Bundled font copyrights:\n${licenseParts.map(([notice])=>notice).join('\n\n')}\n\n${licenseParts[0][1]}\n*/\n`;
css+=`/*! Radix color scale license:\n${readFileSync(root+'node_modules/@radix-ui/colors/LICENSE','utf8')}\n*/\n`;
function font(family,path,weight,style='normal',format='woff2') {
 const data=readFileSync(root+path).toString('base64');
 css+=`@font-face{font-family:'${family}';font-weight:${weight};font-style:${style};font-display:swap;src:url(data:font/${format};base64,${data}) format('${format}');}\n`;
}
// Same Lora release and Latin coverage, with both weights in one face per style.
for(const style of ['normal','italic'])font('Lora',`node_modules/@fontsource-variable/lora/files/lora-latin-wght-${style}.woff2`,'400 700',style);
font('Geist Mono','node_modules/@fontsource/geist-mono/files/geist-mono-latin-400-normal.woff2',400);
font('Chakra Petch','node_modules/@fontsource/chakra-petch/files/chakra-petch-latin-400-normal.woff2',400);
css+=block('body',sharedDesign);
for(const mode of ['light','dark']){
 const tokens=themeTokens(defaults,mode);
 css+=block(`.theme-${mode}`,adapterTokens({
 ...tokens,...obsidianColors(tokens),
 '--arc-control-face':'var(--gray-3)',
 '--arc-edge-high':mode==='dark'?'var(--gray-7)':'#ffffff',
 '--arc-edge-low':mode==='dark'?'#070a09':'#a8b5af',
 '--arc-inset-high':mode==='dark'?'#070a09':'#a8b5af',
 '--arc-inset-low':mode==='dark'?'#47504b':'#ffffff',
 '--arc-accent-high':'var(--arc-obs-primary-8)','--arc-accent-low':'var(--arc-obs-primary-6)',
 '--arc-raised':'inset 1px 1px 0 var(--arc-edge-high),inset -1px -1px 0 var(--arc-edge-low)',
 '--arc-pressed':'inset 1px 1px 0 var(--arc-edge-low),inset -1px -1px 0 var(--arc-edge-high)',
}));
}
css+=adapterCss;
// Compact distribution whitespace while retaining complete font and color licenses.
const compact=transformSync(css,{loader:'css',minifyWhitespace:true,legalComments:'inline'});
if(compact.warnings.length)throw new Error(compact.warnings.map(warning=>warning.text).join('\n'));
css=compact.code;
writeFileSync(output+'theme.css',css);
const version=JSON.parse(readFileSync(root+'package.json','utf8')).version;
const manifest={name:'Arcubic',version,minAppVersion:'1.8.0',author:'Trainvent',authorUrl:'https://github.com/Trainvent'};
writeFileSync(output+'manifest.json',JSON.stringify(manifest,null,2)+'\n');
// Obsidian's community directory reads these from the repository root.
writeFileSync(root+'manifest.json',JSON.stringify(manifest,null,2)+'\n');
writeFileSync(root+'theme.css',css);
let versions={};
try{versions=JSON.parse(readFileSync(root+'versions.json','utf8'));}catch(error){if(error.code!=='ENOENT')throw error;}
versions[manifest.version]=manifest.minAppVersion;
writeFileSync(root+'versions.json',JSON.stringify(versions,null,2)+'\n');
for(const font of fonts)copyFileSync(root+`node_modules/${font.package}/LICENSE`,root+`ports/obsidian/licenses/${font.name}-OFL.txt`);
console.log(`Built ${output}theme.css (${Buffer.byteLength(css).toLocaleString('en-US')} bytes)`);
